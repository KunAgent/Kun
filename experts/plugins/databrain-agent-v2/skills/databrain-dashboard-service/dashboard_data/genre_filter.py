GENRE_MAP_LOWER_DICT = {k.lower(): v for k, v in GENRE_MAP_DICT.items()}

# 从 MAIN_GENRE_DICT 自动生成子类型到主类型的映射
SUB_GENRE_DICT = {}
for main_genre, sub_genres in MAIN_GENRE_DICT.items():
    for sub_genre in sub_genres:
        if sub_genre not in SUB_GENRE_DICT:
            SUB_GENRE_DICT[sub_genre] = []
        SUB_GENRE_DICT[sub_genre].append(main_genre)

sub_genre_filter_lower = {k.lower(): k for k in SUB_GENRE_DICT.keys()}
main_genre_filter_lower = {k.lower(): k for k in MAIN_GENRE_DICT.keys()}
genre_rename_lower = {k.lower(): v for k, v in GENRE_NAME_MAP.items()}


def process_genre_case_insensitive(genre_input: str) -> tuple[list, list]:
    """
    大小写不敏感的品类处理函数

    Args:
        genre_input: 输入的品类名称（支持任意大小写）

    Returns:
        list: 标准化的品类过滤器列表，格式为 [{"genre": "主品类", "sub_genre": ["子品类"]}]

    Examples:
        >>> process_genre_case_insensitive("fps")
        [{'genre': 'Action', 'sub_genre': ['FPS']}, {'genre': 'Gacha', 'sub_genre': ['FPS']}, {'genre': 'RPG', 'sub_genre': ['FPS']}, {'genre': 'Shooter', 'sub_genre': ['FPS']}, {'genre': 'Simulation', 'sub_genre': ['FPS']}]
        >>> process_genre_case_insensitive("MOBA")
        [{'genre': 'Action', 'sub_genre': ['MOBA']}, {'genre': 'Shooter', 'sub_genre': ['MOBA']}, {'genre': 'Strategy', 'sub_genre': ['MOBA']}]
        >>> process_genre_case_insensitive("casual")
        [{'genre': 'Casual', 'sub_genre': []}]
    """
    genre_lower = genre_input.lower()

    # 创建大小写不敏感的查找字典

    # 处理品类名称映射
    if genre_lower in genre_rename_lower:
        genre_lower = genre_rename_lower[genre_lower].lower()

    genres_dict_list = []
    if genre_lower in GENRE_MAP_LOWER_DICT:
        genre_result = GENRE_MAP_LOWER_DICT[genre_lower]
        if isinstance(genre_result, dict):
            genres_dict_list.append(genre_result)
        elif isinstance(genre_result, list):
            genres_dict_list.extend(genre_result)
    elif genre_lower in main_genre_filter_lower:
        # 如果是主品类，则直接添加
        correct_main_genre = main_genre_filter_lower[genre_lower]
        genres_dict_list.append({"genre": correct_main_genre, "sub_genre": []})
    elif genre_lower in sub_genre_filter_lower:
        # 如果是子品类，则需要添加主品类
        correct_sub_genre = sub_genre_filter_lower[genre_lower]
        sub_to_main_genre_list = SUB_GENRE_DICT[correct_sub_genre]
        for main_genre in sub_to_main_genre_list:
            genres_dict_list.append(
                {"genre": main_genre, "sub_genre": [correct_sub_genre]}
            )
    else:
        # 未找到匹配的品类
        raise ValueError(f"无法识别的品类: {genre_input}")

    return genres_dict_list


def process_genres_case_insensitive(genre_inputs: list[str]) -> list[dict]:
    """
    批量处理多个品类，返回标准化的品类过滤器格式

    Args:
        genre_inputs: 输入的品类名称列表（支持任意大小写）

    Returns:
        list: 标准化的品类过滤器列表，格式为 [{"genre": "主品类", "sub_genre": ["子品类"]}]

    Examples:
        >>> process_genres_case_insensitive(["fps", "moba"])
        [{"genre": "Action", "sub_genre": ["FPS"]},
         {"genre": "Gacha", "sub_genre": ["FPS"]},
         {"genre": "RPG", "sub_genre": ["FPS"]},
         {"genre": "Shooter", "sub_genre": ["FPS"]},
         {"genre": "Simulation", "sub_genre": ["FPS"]},
         {"genre": "Action", "sub_genre": ["MOBA"]},
         {"genre": "Shooter", "sub_genre": ["MOBA"]},
         {"genre": "Strategy", "sub_genre": ["MOBA"]}]
    """
    new_genres = []

    for genre in genre_inputs:
        try:
            new_genres.extend(process_genre_case_insensitive(genre))
        except ValueError as e:
            # 记录错误但继续处理其他品类
            import logging

            logging.warning(f"跳过无法识别的品类: {e}")
            continue

    return new_genres


def validate_genre_case_insensitive(genre_input: str) -> bool:
    """
    验证品类名称是否有效（大小写不敏感）

    Args:
        genre_input: 输入的品类名称

    Returns:
        bool: 是否为有效的品类名称
    """
    try:
        process_genre_case_insensitive(genre_input)
        return True
    except ValueError:
        return False


