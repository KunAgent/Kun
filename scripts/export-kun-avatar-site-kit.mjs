#!/usr/bin/env node
// Copies the Kun avatar catalog and its 256px layer art into the website, so the account page can
// dress the same Kun the desktop app does. The TypeScript catalog here stays the only source of
// truth: run this after changing items, presets or art.
//
//   node scripts/export-kun-avatar-site-kit.mjs --site ../dsgui-admin
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'

const siteIndex = process.argv.indexOf('--site')
if (siteIndex < 0 || !process.argv[siteIndex + 1]) {
  console.error('usage: node scripts/export-kun-avatar-site-kit.mjs --site <website checkout>')
  process.exit(1)
}
const site = resolve(process.argv[siteIndex + 1])
const root = resolve(import.meta.dirname, '..')
const HEADER = '// Generated by DeepSeek-GUI scripts/export-kun-avatar-site-kit.mjs from kun/src/contracts. Do not edit.\n'
const sources = ['kun-avatar-catalog.ts', 'kun-avatar-presets.ts']
const folders = ['base', 'crest', 'face', 'glasses', 'headwear', 'outfit', 'prop', 'scene', 'wing', 'fx', 'icon', 'card', 'container']

const code = join(site, 'src', 'lib', 'kun-avatar')
await mkdir(code, { recursive: true })
for (const name of sources) {
  const text = await readFile(join(root, 'kun', 'src', 'contracts', name), 'utf8')
  await writeFile(join(code, name), HEADER + text)
}
const art = join(site, 'public', 'kun-avatar', '256')
await rm(art, { recursive: true, force: true })
for (const folder of folders) {
  await cp(join(root, 'src', 'asset', 'img', 'kun-avatar', '256', folder), join(art, folder), { recursive: true })
}
console.log(`copied ${sources.length} catalog modules to ${code} and ${folders.length} art folders to ${art}`)
