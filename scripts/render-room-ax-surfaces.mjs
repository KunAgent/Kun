#!/usr/bin/env node
/**
 * Renders every registered agent-visible room surface to
 * dist/room-ax-surfaces.md for text review. Requires a kun build
 * (`npm run build:kun`); the artifact is generated, never committed.
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

let registry
try {
  registry = await import(join(root, 'kun', 'dist', 'rooms', 'room-ax-surfaces.js'))
} catch (error) {
  console.error('Cannot load kun/dist/rooms/room-ax-surfaces.js; run `npm run build:kun` first.')
  console.error(error instanceof Error ? error.message : String(error))
  process.exit(1)
}

const { ROOM_AX_SURFACES } = registry

const lines = [
  '# Room agent-visible text surfaces',
  '',
  'Generated by `scripts/render-room-ax-surfaces.mjs` from `kun/src/rooms/room-ax-surfaces.ts`.',
  'Do not edit this file; change the registry and regenerate.',
  ''
]

for (const surface of ROOM_AX_SURFACES) {
  lines.push(`## ${surface.id}`, '', `- kind: ${surface.kind}`, `- description: ${surface.description}`, '')
  for (const example of surface.examples) {
    const rendered = surface.render(example.input)
    lines.push(`### Example: ${example.name}`, '', '```text', rendered, '```', '')
  }
}

const output = join(root, 'dist', 'room-ax-surfaces.md')
await mkdir(dirname(output), { recursive: true })
await writeFile(output, lines.join('\n'))
console.log(`Wrote ${ROOM_AX_SURFACES.length} surfaces to ${output}`)
