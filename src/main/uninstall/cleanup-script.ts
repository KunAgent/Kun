import { randomUUID } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import type { UninstallRemoveAppMode } from '../../shared/uninstall'
import { ONE_SHOT_HELPER_TIMEOUT_SECONDS, powershellHelperDeadline } from '../one-shot-helper-script'

export type CleanupRequest = {
  operationId: string
  mainPid: number
  /** Recorded for diagnostics. A cleanup helper never force-kills a live GUI. */
  guardCommandSubstring: string
  /** Validated absolute paths (already passed assertSafeUninstallPath). */
  deleteDataPaths: string[]
  appRemovalMode: UninstallRemoveAppMode
  appRemovalTarget?: string
  platform: NodeJS.Platform
  tempRoot: string
  /** Marker directory that the script removes last (set by writeCleanupScripts). */
  markerDir: string
  /** Test seam; production helpers use the bounded five-minute handoff. */
  helperTimeoutSeconds?: number
  mainWaitSeconds?: number
}

export type CleanupScriptOutput = {
  markerDir: string
  markerPath: string
  scriptPath: string
}

const PID_WAIT_POLL_SECONDS = 0.5
const WINDOWS_WAIT_SECONDS = 90

function shellSingleQuote(value: string): string {
  return `'${value.replace(/'/gu, `'\\''`)}'`
}

function powershellSingleQuote(value: string): string {
  return `'${value.replace(/'/gu, "''")}'`
}

export function buildPosixCleanupScript(request: CleanupRequest): string {
  const lifetime = request.helperTimeoutSeconds ?? ONE_SHOT_HELPER_TIMEOUT_SECONDS
  if (!Number.isInteger(lifetime) || lifetime < 1 || lifetime > 3_600) throw new Error('Invalid helper deadline')
  const waitPolls = Math.max(1, Math.ceil((request.mainWaitSeconds ?? 60) / PID_WAIT_POLL_SECONDS))
  const lines: string[] = [
    '#!/bin/sh',
    '# Generated by Kun uninstall. Do not edit.',
    'set -eu',
    'HELPER_PID=$$',
    'GROUP_PID=$(ps -p "$$" -o pgid= | tr -d " ")',
    '[ "$GROUP_PID" = "$HELPER_PID" ] || exit 125',
    `WATCHDOG_READY=${shellSingleQuote(join(request.markerDir, 'watchdog.ready'))}`,
    '(',
    '  timer=',
    "  trap 'kill \"$timer\" 2>/dev/null || true; wait \"$timer\" 2>/dev/null || true; exit 0' TERM INT HUP",
    `  sleep ${lifetime} & timer=$!`,
    '  : > "$WATCHDOG_READY"',
    '  wait "$timer"',
    '  kill -KILL "-$HELPER_PID" 2>/dev/null || true',
    ') &',
    'WATCHDOG_PID=$!',
    "trap 'code=$?; trap - EXIT; kill -TERM \"$WATCHDOG_PID\" 2>/dev/null || true; wait \"$WATCHDOG_PID\" 2>/dev/null || true; exit \"$code\"' EXIT",
    "trap 'exit 130' INT",
    "trap 'exit 143' TERM HUP",
    'while [ ! -f "$WATCHDOG_READY" ]; do',
    '  kill -0 "$WATCHDOG_PID" 2>/dev/null || exit 125',
    '  sleep 0.01',
    'done',
    `MAIN_PID=${request.mainPid}`,
    `GUARD=${shellSingleQuote(request.guardCommandSubstring)}`,
    'i=0',
    'while kill -0 "$MAIN_PID" 2>/dev/null; do',
    '  i=$((i+1))',
    `  if [ "$i" -ge ${waitPolls} ]; then exit 124; fi`,
    `  sleep ${PID_WAIT_POLL_SECONDS}`,
    'done',
    'sleep 1'
  ]
  for (const path of request.deleteDataPaths) {
    lines.push(`rm -rf -- ${shellSingleQuote(path)}`)
  }
  if (request.appRemovalMode === 'bundle' && request.appRemovalTarget) {
    lines.push(`rm -rf -- ${shellSingleQuote(request.appRemovalTarget)}`)
  } else if (request.appRemovalMode === 'appimage' && request.appRemovalTarget) {
    lines.push(`rm -f -- ${shellSingleQuote(request.appRemovalTarget)}`)
  }
  lines.push(`rm -rf -- ${shellSingleQuote(request.markerDir)}`)
  return `${lines.join('\n')}\n`
}

export function buildWindowsCleanupScript(request: CleanupRequest): string {
  const lines: string[] = [
    '# Generated by Kun uninstall. Do not edit.',
    powershellHelperDeadline(request.helperTimeoutSeconds, true),
    `$mainPid = ${request.mainPid}`,
    `$guard = ${powershellSingleQuote(request.guardCommandSubstring)}`,
    `$deadline = (Get-Date).AddSeconds(${request.mainWaitSeconds ?? WINDOWS_WAIT_SECONDS})`,
    'while ((Get-Process -Id $mainPid -ErrorAction SilentlyContinue) -and ((Get-Date) -lt $deadline)) {',
    '  Start-Sleep -Milliseconds 500',
    '}',
    'if (Get-Process -Id $mainPid -ErrorAction SilentlyContinue) { exit 124 }',
    'Start-Sleep -Seconds 1'
  ]
  for (const path of request.deleteDataPaths) {
    lines.push(`Remove-Item -LiteralPath ${powershellSingleQuote(path)} -Recurse -Force`)
  }
  if (request.appRemovalMode === 'uninstaller' && request.appRemovalTarget) {
    lines.push(`if (Test-Path -LiteralPath ${powershellSingleQuote(request.appRemovalTarget)}) {`)
    lines.push(
      `  $uninstaller = Start-Process -FilePath ${powershellSingleQuote(request.appRemovalTarget)} -ArgumentList '/S' -Wait -PassThru`
    )
    lines.push('  if ($uninstaller.ExitCode -ne 0) { exit $uninstaller.ExitCode }')
    lines.push('}')
  }
  lines.push(`Remove-Item -LiteralPath ${powershellSingleQuote(request.markerDir)} -Recurse -Force`)
  return `${lines.join('\n')}\n`
}

export async function writeCleanupScripts(
  request: Omit<CleanupRequest, 'markerDir'>
): Promise<CleanupScriptOutput> {
  const operationId = request.operationId || randomUUID()
  const markerDir = join(request.tempRoot, `kun-uninstall-${operationId}`)
  await mkdir(markerDir, { recursive: true })
  const isWindows = request.platform === 'win32'
  const scriptName = isWindows ? 'cleanup.ps1' : 'cleanup.sh'
  const scriptPath = join(markerDir, scriptName)
  const markerPath = join(markerDir, 'marker.json')
  const marker = {
    schemaVersion: 1,
    operationId,
    mainPid: request.mainPid,
    guardCommandSubstring: request.guardCommandSubstring,
    deleteDataPaths: request.deleteDataPaths,
    appRemovalMode: request.appRemovalMode,
    appRemovalTarget: request.appRemovalTarget ?? null,
    platform: request.platform,
    createdAt: new Date().toISOString()
  }
  const script = isWindows
    ? buildWindowsCleanupScript({ ...request, operationId, markerDir })
    : buildPosixCleanupScript({ ...request, operationId, markerDir })
  await writeFile(markerPath, `${JSON.stringify(marker, null, 2)}\n`, 'utf8')
  await writeFile(scriptPath, script, 'utf8')
  return { markerDir, markerPath, scriptPath }
}
