import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { EVENT_FRAME_SPACING_MS, EventCoalescer } from './event-coalescer'

beforeEach(() => vi.useFakeTimers())
afterEach(() => vi.useRealTimers())
const delta = (seq: number) => ({ kind: 'item.delta', seq })

describe('relayed event coalescing', () => {
  it('sends the first event at once and then the newest event at most once per spacing', async () => {
    const send = vi.fn(), events = new EventCoalescer(send, vi.fn())
    events.push(delta(1))
    expect(send.mock.calls.map(([event]) => event.seq)).toEqual([1])
    for (let seq = 2; seq <= 40; seq++) events.push(delta(seq))
    expect(send).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(EVENT_FRAME_SPACING_MS - 1)
    expect(send).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(1)
    expect(send.mock.calls.map(([event]) => event.seq)).toEqual([1, 40])
    await vi.advanceTimersByTimeAsync(EVENT_FRAME_SPACING_MS * 5)
    expect(send).toHaveBeenCalledTimes(2)
  })
  it('bounds a fast token stream to the spacing and still delivers its last cursor', async () => {
    const send = vi.fn(), events = new EventCoalescer(send, vi.fn())
    // 2000 deltas at one every 10 ms: a 20 s reply streamed at 100 deltas/s.
    for (let seq = 1; seq <= 2000; seq++) {
      events.push(delta(seq))
      await vi.advanceTimersByTimeAsync(10)
    }
    await vi.advanceTimersByTimeAsync(EVENT_FRAME_SPACING_MS)
    expect(send.mock.calls.length).toBeLessThanOrEqual(20000 / EVENT_FRAME_SPACING_MS + 1)
    expect(send.mock.calls.at(-1)![0].seq).toBe(2000)
    const seqs = send.mock.calls.map(([event]) => event.seq)
    expect(seqs).toEqual([...seqs].sort((a, b) => a - b))
  })
  it('never lets a heartbeat or replay marker displace persisted work held for the next frame', async () => {
    const send = vi.fn(), events = new EventCoalescer(send, vi.fn())
    events.push(delta(1))
    events.push(delta(2))
    events.push({ kind: 'heartbeat', seq: 2 })
    events.push({ kind: 'replay_synchronized', cursor: 2 })
    events.push({ threadId: 'thread', floorSeq: 1 })
    await vi.advanceTimersByTimeAsync(EVENT_FRAME_SPACING_MS)
    expect(send.mock.calls.map(([event]) => event)).toEqual([delta(1), delta(2)])
    events.push({ kind: 'heartbeat', seq: 2 })
    await vi.advanceTimersByTimeAsync(EVENT_FRAME_SPACING_MS)
    events.push({ kind: 'heartbeat', seq: 2 })
    events.push({ kind: 'replay_synchronized', cursor: 2 })
    await vi.advanceTimersByTimeAsync(EVENT_FRAME_SPACING_MS)
    expect(send.mock.calls.slice(2).map(([event]) => event.kind)).toEqual(['heartbeat', 'replay_synchronized'])
  })
  it('flushes the held event on demand and sends nothing after stop', async () => {
    const send = vi.fn(), events = new EventCoalescer(send, vi.fn())
    events.push(delta(1))
    events.push(delta(2))
    events.flush()
    expect(send.mock.calls.map(([event]) => event.seq)).toEqual([1, 2])
    events.push(delta(3))
    events.stop()
    events.push(delta(4))
    events.flush()
    await vi.advanceTimersByTimeAsync(EVENT_FRAME_SPACING_MS * 2)
    expect(send).toHaveBeenCalledTimes(2)
  })
  it('throws a failed immediate send to the caller and reports a failed deferred send once', async () => {
    const failed = vi.fn(), send = vi.fn(() => { throw new Error('SEND_FAILED') })
    const events = new EventCoalescer(send, failed)
    expect(() => events.push(delta(1))).toThrow('SEND_FAILED')
    events.push(delta(2))
    await vi.advanceTimersByTimeAsync(EVENT_FRAME_SPACING_MS)
    expect(failed).toHaveBeenCalledOnce()
    events.push(delta(3))
    await vi.advanceTimersByTimeAsync(EVENT_FRAME_SPACING_MS)
    expect(send).toHaveBeenCalledTimes(2)
  })
})
