export function instanceText(instance: ReactTestInstance): string {
  return instance.children
    .map((child) => typeof child === 'string' ? child : instanceText(child))
    .join('')
}

export function rendererText(renderer: ReactTestRenderer): string {
  return JSON.stringify(renderer.toJSON())
}

export function findButton(renderer: ReactTestRenderer, label: string): ReactTestInstance {
  const button = renderer.root.findAllByType('button')
    .find((candidate) => instanceText(candidate).trim() === label)
  expect(button, `button "${label}"`).toBeTruthy()
  return button!
}

export function findButtonContaining(renderer: ReactTestRenderer, label: string): ReactTestInstance {
  const button = renderer.root.findAllByType('button')
    .find((candidate) => instanceText(candidate).includes(label))
  expect(button, `button containing "${label}"`).toBeTruthy()
  return button!
}

export function activePanelText(renderer: ReactTestRenderer): string {
  const panels = renderer.root
    .findAllByProps({ role: 'tabpanel' })
    .filter((panel) => String(panel.props.id ?? '').startsWith('provider-settings-panel-'))
    .filter((panel) => panel.props.hidden !== true)
  expect(panels).toHaveLength(1)
  return instanceText(panels[0])
}

