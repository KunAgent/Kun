export function t(key: string, params?: Record<string, unknown>): string {
  let value = labels[key] ?? key
  for (const [name, replacement] of Object.entries(params ?? {})) {
    value = value.split(`{{${name}}}`).join(String(replacement))
  }
  return value
}

